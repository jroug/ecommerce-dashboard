import type { Customer, CustomerAddress } from "@/types/customer";

const address = (
  city: string,
  country: string,
  countryCode: string,
  postcode: string,
): CustomerAddress => ({
  address1: "12 Market Street",
  address2: "",
  city,
  state: "",
  postcode,
  country,
  countryCode,
});
const customer = (
  id: number,
  firstName: string,
  lastName: string,
  email: string,
  phone: string,
  dateCreated: string,
  city: string,
  country: string,
  countryCode: string,
  postcode: string,
  ordersCount: number,
  totalSpent: string,
  lastOrderDate: string | null,
  tags: string[] = [],
): Customer => {
  const billing = address(city, country, countryCode, postcode);
  return {
    id,
    firstName,
    lastName,
    email,
    phone,
    avatar: null,
    dateCreated,
    billing,
    shipping: { ...billing },
    ordersCount,
    totalSpent,
    averageOrderValue: ordersCount ? (Number(totalSpent) / ordersCount).toFixed(2) : "0.00",
    lastOrderDate,
    tags,
    currency: "EUR",
  };
};

